"""For challenge found at https://adventofcode.com/2024/day/11"""

import os
import sys
import math

# Fallback to script directory if current working directory is incorrect
# Basically keeps me from encountering errors during debugging

script_dir = os.path.dirname(sys.argv[0])
file_path = os.path.join(script_dir, "input_files/day_11.txt")

with open(file_path, "r") as file:
    puzzle = file.read().strip()
    # returns as single string

def prep_data(data):
    """Splits string into integers"""
    nums = [int(x) for x in data.split()]
    return nums 

stone_dict = {}
# keeps track of combos of stone with blinks remaining has already occurred
# to prevent unnecessary recalculations

def stone_calc(stone, blinks_remaining):
    """
    Calculates the number of stones generated by a single starting stone
    over a series of blinks
    """
    
    global stone_dict

    # to avoid recalculations
    if (stone, blinks_remaining) in stone_dict:
        return stone_dict[(stone, blinks_remaining)]
    
    # exit condition = last stone remaining
    if blinks_remaining == 0:
        stone_dict[(stone, blinks_remaining)] = 1
        return 1
    # stones with 0 become stones with 1
    if stone == 0:
        result = stone_calc(1, blinks_remaining-1)
        stone_dict[(stone, blinks_remaining)] = result
        return result
    
    # calculating number of digits
    stone_digits = int(math.log10(abs(stone))) + 1 

    # if even number of digits, splits into two stones
    if stone_digits % 2 == 0 and stone_digits != 0:
        first_stone = int(stone // (10 ** (stone_digits / 2)))
        second_stone = int(stone - (first_stone * (10 ** (stone_digits / 2))))
        first_result = stone_calc(first_stone,blinks_remaining-1)
        second_result = stone_calc(second_stone,blinks_remaining-1)
        total_result = first_result + second_result
        stone_dict[((stone, blinks_remaining))] = total_result
        return total_result
    
    # all other numbers
    else:
        result = stone_calc(stone * 2024, blinks_remaining-1)
        return result
    
stones = prep_data(puzzle)
final_stones = 0
for stone in stones:
    result = stone_calc(stone,25)
    final_stones += result

print(final_stones)
